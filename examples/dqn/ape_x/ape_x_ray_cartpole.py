"""
Notes on Ape-X DQN:
Ape-X is a distributed reinforcement learning architecture that combines:
1. Prioritized Experience Replay (PER) for prioritized sampling
2. Distributed actors for parallel experience collection
3. Centralized learner for efficient optimization

Key differences from standard DQN:
1. Actors collect experiences in parallel and push them to a shared buffer
2. The learner samples from the shared buffer and updates the network
3. Actors periodically sync weights from the learner
4. N-step returns are used to improve sample efficiency
5. Dueling DQN architecture is used to improve performance

The main goal of the paper was to show that a centralized learner could train agents more efficiently
by leveraging the parallel experience collection of multiple actors. Essentially, it was to reduce wall clock time by having many actors collect data in parallel. There were a few DQN specific changes (like different values of epsilon for each actor) to improve performance. Ape-X also introduced online priority calculation in the actors instead of using the base max priority. By doing this it removes the focus on the most recent data in the buffer, and instead focuses on the most important data in the buffer. This comes at no cost to the learner. To prevent network or IPC (Inter-Process Communication) bottlenecks, actors do not send single transitions to the replay buffer. They batch experience data locally (e.g., chunks of 50 or 100 transitions) and send them asynchronously, drastically reducing the overhead on the centralized server.

The paper also showed that the recency of the data was not the cause of the increased performance, but the quantity and scale of the data was infact the reason for the increased performance.

The Ape-X framework is algorithm-agnostic. The authors proved this by successfully scaling DDPG (Ape-X DPG) for continuous control tasks alongside DQN, showing that the decoupled actor/learner and prioritized replay framework generalizes across discrete and continuous action spaces.

This technique is now standard practice for training deep reinforcement learning agents at scale. AlphaZero, MuZero, and other state of the art algorithms use similar architectures (in terms of distributed actors and a central learner/server). The use of the online priority calculation is less common in other algorithms. In terms of the different values of epsilon, this does not generally apply to algorithms that don't use epsilon greedy, however it could feasibly be applied in some way to other algorithms as well, where each actor is assigned a different exploration parameter (for example different tau for temperature sampling exploration). Since Ape-X, the industry realized that pre-allocating a massive, contiguous block of memory (a Tensor) and overwriting it in a circle is vastly superior for memory management and CPU caching (similar to what we do here in our implementation).

Something to note is that Ape-X strictly requires off-policy algorithms. Because data is generated by delayed networks using vastly different exploration parameters, on-policy algorithms (like standard PPO or A2C) would fail or suffer severe performance degradation in this architecture.

One thing to note there are some different ways of implementing distributed RL systems. This is one possible implementation. Some implementations also use a seperate process/node for the replay buffer, and seperate process/node for the shared parameter storage. This is especially true when using something like Ray for distributed computing.

NOTE: The original paper did not use a circular buffer for the replay buffer. It used a buffer with a "target" capacity, and allowed for overflow, every 100 steps it would flush the overflow from the buffer in a FIFO manner. This is in contrast to the implementation here which uses a circular buffer and doesn't allow for overflow. The paper used a key value buffer and so removed all old transitions at once and allowed for overflow of the buffer. We are using a circular buffer for simplicity, with our current pytorch based buffers, this would be inefficient.

NOTE: Our implementation uses ray which was not available at the time of the paper but is now widely used and makes the implementation much cleaner.

"""

